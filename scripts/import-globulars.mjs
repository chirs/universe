// Import the Harris (1996, 2010 edition) Milky Way globular cluster catalog
// and write www/js/globulars.js. Usage: node scripts/import-globulars.mjs
import { writeFileSync } from 'node:fs';

const URL_ = 'https://physics.mcmaster.ca/~harris/mwgc.dat';
const text = await (await fetch(URL_)).text();
const lines = text.split('\n');
const part = (title) => {
  const start = lines.findIndex((l) => l.includes(title));
  const header = lines.findIndex((l, i) => i > start && l.trim().startsWith('ID'));
  const rows = [];
  for (let i = header + 1; i < lines.length; i++) {
    if (/^\s*Part /.test(lines[i]) || /^_{5,}/.test(lines[i].trim())) break;
    if (lines[i].trim()) rows.push(lines[i]);
  }
  return rows;
};

// Part I is fixed-width: ID, then name, then whitespace-separated fields.
const clusters = new Map();
for (const row of part('Part I:')) {
  const id = row.slice(0, 12).trim();
  const name = row.slice(12, 25).trim();
  const f = row.slice(25).trim().split(/\s+/);
  // RA h m s, Dec d m s, L, B, R_Sun, ...
  const [l, b, dist] = [Number(f[6]), Number(f[7]), Number(f[8])];
  if (!Number.isFinite(dist)) continue;
  clusters.set(id, { id, name, l, b, dist });
}
// Part II: absolute visual magnitude M_V,t in its fixed column.
const p2 = part('Part II:');
for (const row of p2) {
  const id = row.slice(0, 12).trim();
  const mv = Number(row.slice(46, 54));
  if (clusters.has(id) && row.slice(46, 54).trim() && Number.isFinite(mv)) clusters.get(id).mv = mv;
}

const out = [...clusters.values()].map((c) =>
  `  [${JSON.stringify(c.id)}, ${JSON.stringify(c.name)}, ${c.l}, ${c.b}, ${c.dist}, ${c.mv ?? 'null'}],`);
writeFileSync(new URL('../www/js/globulars.js', import.meta.url), `// Generated by scripts/import-globulars.mjs from Harris 1996 (2010 edition),
// ${URL_}, on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Per cluster: catalog ID, common name, galactic l and b (degrees), distance
// from the Sun (kpc), absolute visual magnitude M_V (null where not listed).
export const GLOBULAR_CLUSTERS = [
${out.join('\n')}
];
`);
console.log(`${clusters.size} clusters, ${[...clusters.values()].filter((c) => c.mv !== undefined).length} with M_V`);
