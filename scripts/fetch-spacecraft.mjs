// Fetch spacecraft tracks from JPL Horizons and write www/js/spacecraft.js.
// Usage: node scripts/fetch-spacecraft.mjs
import { writeFileSync } from 'node:fs';
import { SPACECRAFT } from '../www/js/data.js';

const API = 'https://ssd.jpl.nasa.gov/api/horizons.api';
const J2000_JD = 2451545.0;
const FAR = '2100-01-01';

async function query(sc, start, stop) {
  const params = {
    format: 'text', COMMAND: `'${sc.horizons}'`, OBJ_DATA: 'NO', MAKE_EPHEM: 'YES', EPHEM_TYPE: 'VECTORS',
    CENTER: `'500@${sc.center || 10}'`, START_TIME: `'${start}'`, STOP_TIME: `'${stop}'`, STEP_SIZE: `'${Math.round(sc.step * 1440)} m'`,
    VEC_TABLE: '1', REF_PLANE: 'ECLIPTIC', OUT_UNITS: 'AU-D', CSV_FORMAT: 'YES',
  };
  const url = `${API}?${new URLSearchParams(params)}`;
  const text = await (await fetch(url)).text();
  return text;
}

// Horizons names the first and last epochs it covers when asked outside them.
function bound(text, word) {
  const m = text.match(new RegExp(`${word} A\\.D\\. (\\d{4}-[A-Z]{3}-\\d{2}) (\\d{2}:\\d{2})`));
  return m && `${m[1]} ${m[2]}`;
}

function addDays(date, days) {
  const t = new Date(date.replace(/-([A-Z]{3})-/, (_, mon) => `-${mon[0]}${mon.slice(1).toLowerCase()}-`) + 'Z');
  return new Date(t.getTime() + days * 864e5).toISOString().slice(0, 16).replace('T', ' ');
}

async function track(sc) {
  let start = sc.from || '1970-01-01';
  let stop = FAR;
  for (let attempt = 0; attempt < 4; attempt++) {
    const text = await query(sc, start, stop);
    const soe = text.indexOf('$$SOE');
    if (soe >= 0) {
      const rows = text.slice(soe + 5, text.indexOf('$$EOE')).trim().split('\n').map((line) => line.split(',').map((f) => f.trim()));
      const lon = [];
      const r = [];
      for (const [jd, , x, y, z] of rows) {
        lon.push(Number((((Math.atan2(+y, +x) * 180 / Math.PI) + 360) % 360).toFixed(2)));
        r.push(Number(Math.hypot(+x, +y, +z).toPrecision(5)));
      }
      return { start: Number((+rows[0][0] - J2000_JD).toFixed(4)), step: sc.step, lon, r };
    }
    const first = bound(text, 'prior to');
    const last = bound(text, 'after');
    if (first) start = addDays(first, 1);
    else if (last) stop = addDays(last, -1);
    else throw new Error(`${sc.name}: ${text.slice(0, 400)}`);
  }
  throw new Error(`${sc.name}: no coverage found`);
}

const tracks = {};
for (const sc of SPACECRAFT) {
  tracks[sc.name] = await track(sc);
  const t = tracks[sc.name];
  const end = new Date((J2000_JD - 2440587.5 + t.start + (t.lon.length - 1) * t.step) * 864e5).toISOString().slice(0, 10);
  const soon = new Date(end) - Date.now() < 90 * 864e5 ? ' (ends soon; rerun to extend)' : '';
  console.log(`${sc.name}: ${t.lon.length} samples from J2000${t.start >= 0 ? '+' : ''}${t.start} d to ${end}${soon}`);
}
const header = `// Generated by scripts/fetch-spacecraft.mjs from JPL Horizons on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand. Per craft: start (days since J2000, TDB), step (days),
// then ecliptic longitude (degrees, J2000 ecliptic) and true distance from the
// center body (AU) at each sample. Latitude is dropped, distance kept.
`;
const body = Object.entries(tracks).map(([name, t]) =>
  `  ${JSON.stringify(name)}: { start: ${t.start}, step: ${t.step},\n    lon: [${t.lon.join(',')}],\n    r: [${t.r.join(',')}] },`).join('\n');
writeFileSync(new URL('../www/js/spacecraft.js', import.meta.url), `${header}export const TRACKS = {\n${body}\n};\n`);
