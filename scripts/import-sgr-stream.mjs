// Import the Gaia catalog of Sagittarius stream stars (Vasiliev et al. 2021,
// VizieR J/MNRAS/501/2279) and write www/js/sgrstream.js. Distances there
// come from nearby RR Lyrae, so neighbours share one estimate and the stream
// would draw as stripes; each star is placed instead at a seeded draw from
// its own distance and error. The dwarf galaxy's core holds most of the
// stars and is drawn by the Local Group layer, so it is thinned hard; the
// stream is thinned lightly. Usage: node scripts/import-sgr-stream.mjs
import { writeFileSync } from 'node:fs';
import { mulberry32 } from '../www/js/util.js';

const URL_ = 'https://vizier.cds.unistra.fr/viz-bin/asu-tsv?-source=J/MNRAS/501/2279/catalog'
  + '&-out.max=unlimited&-out=Dist,e_Dist&-out.add=_Glon,_Glat';
const CORE = { l: 5.6, b: -14.2, radius: 12 };   // the Sagittarius Dwarf, degrees
const text = await (await fetch(URL_)).text();
const rows = text.split('\n').filter((l) => l && !l.startsWith('#')).slice(3);

const D2R = Math.PI / 180;
const angle = (l1, b1, l2, b2) => Math.acos(Math.min(1, Math.sin(b1 * D2R) * Math.sin(b2 * D2R)
  + Math.cos(b1 * D2R) * Math.cos(b2 * D2R) * Math.cos((l1 - l2) * D2R))) / D2R;
const rand = mulberry32(8);
const gaussian = () => Math.sqrt(-2 * Math.log(1 - rand())) * Math.cos(2 * Math.PI * rand());
const out = [];
let core = 0;
let stream = 0;
for (const row of rows) {
  const [l, b, mean, err] = row.split('\t').map(Number);
  if (!Number.isFinite(mean)) continue;
  const inCore = angle(l, b, CORE.l, CORE.b) < CORE.radius;
  // Every 40th core star, every 3rd stream star, in catalog order.
  if (inCore ? core++ % 40 : stream++ % 3) continue;
  const dist = mean + gaussian() * (err || 0);
  out.push(`${l.toFixed(2)},${dist.toFixed(2)}`);
}
writeFileSync(new URL('../www/js/sgrstream.js', import.meta.url), `// Generated by scripts/import-sgr-stream.mjs from Vasiliev et al. 2021
// (VizieR J/MNRAS/501/2279) on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Sagittarius stream stars, thinned: galactic longitude (degrees) and
// distance from the Sun (kpc, a seeded draw within the catalog's error),
// in pairs. Every 40th star within 12 degrees of the dwarf's core is kept
// and every 3rd beyond it.
export const SGR_STREAM = [
${out.join(',\n')},
];
`);
console.log(`${out.length} stars kept of ${core + stream}`);
